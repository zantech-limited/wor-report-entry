import assert from "node:assert/strict";
import {readFileSync,readdirSync} from "node:fs";
import path from "node:path";
import {createHash} from "node:crypto";
import {createBlankReport,getReport,saveReportChecked} from "../src/lib/db";
import {database,dataDirectory} from "../src/lib/storage";
import {newEntryLine,type Report} from "../src/lib/model";
import {writeLocalDraft,readLocalDraft,clearLocalDraft,archiveLocalDraft,draftKey} from "../src/lib/local-draft";
async function main(){
 assert(process.env.DATA_DIR?.includes('.checks'));
 if(process.env.DB_ENGINE&&process.env.DB_ENGINE!=='sqlite')assert(/^desk_test_/.test(process.env.DB_NAME??''));
 let report=await createBlankReport();
 report.lines=Array.from({length:89},(_,i)=>({...newEntryLine(String(i+1)),customer:'Recovery test',date:'2026-09-14'}));
 const first=await saveReportChecked(report.id,report,'when-changed');report={...report,updatedAt:first.updatedAt};
 const stale=structuredClone(report);
 report.lines.push(...Array.from({length:33},(_,i)=>({...newEntryLine(String(i+90)),customer:'Recovery test',date:'2026-09-14'})));
 const second=await saveReportChecked(report.id,report,'when-changed');report.updatedAt=second.updatedAt;
 stale.lines[0].comments='An edit from a cached 89-row page';
 await assert.rejects(()=>saveReportChecked(stale.id,stale),/Save conflict:/);
 assert.equal((await getReport(report.id))!.lines.length,122,'Stale page deleted newly saved jobs');
 const current=(await getReport(report.id))!;
 const a=structuredClone(current),b=structuredClone(current);a.lines[0].comments='A';b.lines[0].comments='B';
 const results=await Promise.allSettled([saveReportChecked(a.id,a,'when-changed'),saveReportChecked(b.id,b,'when-changed')]);
 assert.equal(results.filter(x=>x.status==='fulfilled').length,1);assert.equal(results.filter(x=>x.status==='rejected').length,1);
 const folder=path.join(dataDirectory,'report-history',createHash('sha256').update(report.id).digest('hex'));
 const snapshots=readdirSync(folder).map(file=>JSON.parse(readFileSync(path.join(folder,file),'utf8')).report as Report);
 assert(snapshots.some(r=>r.lines.length===89));assert(snapshots.some(r=>r.lines.length===122));
 const db=await database();const query=db.query.bind(db);
 db.query=async(sql,values)=>{if(sql.includes('SELECT kind, parent, value, uses'))throw new Error('Synthetic autocomplete outage');return query(sql,values);};
 const changed=(await getReport(report.id))!;changed.lines[0].customer='Changed recovery customer';
 const ack=await saveReportChecked(changed.id,changed);db.query=query;
 assert.equal(ack.suggestions,undefined);assert.equal((await getReport(changed.id))!.updatedAt,ack.updatedAt,'Committed save lost its acknowledgement');
 const storage:Record<string,unknown>={getItem(key:string){return typeof this[key]==='string'?this[key]:null;},setItem(key:string,value:string){this[key]=value;},removeItem(key:string){delete this[key];}};
 Object.defineProperty(globalThis,'localStorage',{value:storage,configurable:true});
 assert(writeLocalDraft(report));assert.deepEqual(readLocalDraft(report.id),report);
 assert(archiveLocalDraft(report));clearLocalDraft(report.id);assert.deepEqual(readLocalDraft(report.id),report,'Archived conflict copy disappeared');
 storage.setItem=()=>{throw new Error('Quota exceeded');};assert.equal(writeLocalDraft(stale),false);assert.deepEqual(readLocalDraft(report.id),report);
 storage[draftKey(report.id)]='invalid json';assert.equal(readLocalDraft(report.id),null);
 await db.close();console.log('Save recovery passed: stale 89-row saves cannot replace 122 rows; concurrent edits conflict safely; history, local drafts, quota handling and committed-save acknowledgements preserved.');
}
main().catch(e=>{console.error(e);process.exit(1)});
